#!/usr/bin/env python3
"""Measure a G-code file the way this guide teaches readers to.

    python3 check_gcode.py file.gcode

Reports only things that can be counted in the file itself:
the generator's header line, the layer count two independent
ways (layer-change markers and distinct extrusion heights),
total filament extruded (summed move by move), the footer
estimates the slicer itself wrote, and tool-change commands.
"""
import re
import sys

path = sys.argv[1]
lines = open(path, encoding="utf-8", errors="replace").read().splitlines()

header = next((l for l in lines if "generated by" in l.lower()), "(none)")
layer_markers = sum(1 for l in lines if l.strip() == ";LAYER_CHANGE")
footer = [l.strip() for l in lines
          if re.search(r"filament used|printing time|layer number|"
                       r"layers count|total filament|model printing time",
                       l, re.I)]
tool_changes = {}
for l in lines:
    m = re.fullmatch(r"T(\d+)", l.strip())
    if m:
        tool_changes[m.group(0)] = tool_changes.get(m.group(0), 0) + 1

# Sum extrusion: follow absolute (M82) / relative (M83) E mode and
# honour G92 E resets. Two totals are reported: the gross forward
# travel of the extruder (every push, including the re-push after
# each retraction) and the net figure (signed sum), which is the
# filament that actually left the spool.
relative = False
last_e = 0.0
gross_e = 0.0
net_e = 0.0
cur_z = None
z_values = set()
for l in lines:
    s = l.split(";")[0].strip()
    if s == "M82":
        relative = False
    elif s == "M83":
        relative = True
    elif s.startswith("G92"):
        m = re.search(r"E(-?[\d.]+)", s)
        if m:
            last_e = float(m.group(1))
    elif s.startswith(("G0", "G1", "G2", "G3")):
        zm = re.search(r"Z(-?[\d.]+)", s)
        if zm:
            cur_z = round(float(zm.group(1)), 3)
        em = re.search(r"E(-?[\d.]+)", s)
        if em and s.startswith("G1"):
            e = float(em.group(1))
            if relative:
                delta = e
            else:
                delta = e - last_e
                last_e = e
            net_e += delta
            if delta > 0:
                gross_e += delta
                if cur_z is not None:
                    z_values.add(cur_z)

print(f"file: {path}")
print(f"lines: {len(lines)}")
print(f"header: {header.strip()}")
print(f"layer-change markers (;LAYER_CHANGE): {layer_markers}")
print(f"distinct extrusion heights: {len(z_values)}")
print(f"filament extruded, net (signed sum of moves): {net_e:.1f} mm "
      f"({net_e / 1000:.2f} m)")
print(f"filament pushed, gross (forward moves only): {gross_e:.1f} mm")
print(f"tool changes: {tool_changes if tool_changes else 'none'}")
print("slicer's own footer lines:")
for l in footer:
    print(f"  {l}")
